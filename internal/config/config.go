package config

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/BurntSushi/toml"
)

const (
	DefaultURL    = "https://review.opendev.org"
	DefaultBugURL = "https://bugs.launchpad.net/bugs/{id}"

	// DefaultDiffCommand shows a real git diff between the before and after
	// trees, which honours the user's git pager and colour settings.
	DefaultDiffCommand = "git diff --no-index --no-prefix {old} {new}"
)

// ErrNotFound means no config file exists and no URL was given by environment.
var ErrNotFound = errors.New("no config file")

type Config struct {
	Gerrit   Gerrit   `toml:"gerrit"`
	Diff     Diff     `toml:"diff"`
	Bugs     Bugs     `toml:"bugs"`
	Messages Messages `toml:"messages"`
	Filters  []Filter `toml:"filters"`
}

type Gerrit struct {
	URL      string `toml:"url"`
	Username string `toml:"username"`
	Token    string `toml:"token"`
}

// Diff configures the external diff viewer. Command runs through the shell
// in a temporary directory holding the change; {old} and {new} expand to the
// before and after trees, {patch} to a unified patch file, {notes} to the
// inline comments as a hunk agent-context sidecar. A command using no
// placeholder receives the patch on stdin.
type Diff struct {
	Command string `toml:"command"`
}

func (d Diff) CommandOrDefault() string {
	if d.Command == "" {
		return DefaultDiffCommand
	}
	return d.Command
}

// Bugs sets where "Closes-Bug: #id" style footers link to; {id} is replaced.
type Bugs struct {
	URL string `toml:"url"`
}

func (b Bugs) URLOrDefault() string {
	if b.URL == "" {
		return DefaultBugURL
	}
	return b.URL
}

// Messages tunes how change messages are classified. Bots lists account
// names or usernames whose messages count as automated, on top of messages
// Gerrit tags as autogenerated and authors whose name ends in " CI".
type Messages struct {
	Bots []string `toml:"bots"`
}

// Filter is a named change query shown as a dashboard tab.
type Filter struct {
	Name  string `toml:"name"`
	Query string `toml:"query"`
}

var DefaultFilters = []Filter{
	{Name: "My changes", Query: "owner:self"},
	{Name: "Reviewing", Query: "reviewer:self -owner:self"},
	{Name: "Starred", Query: "is:starred"},
}

// AnonymousFilters are used without credentials, since "self" queries need
// an account.
var AnonymousFilters = []Filter{{Name: "Open changes", Query: "is:open"}}

func (c Config) FiltersOrDefault() []Filter {
	switch {
	case len(c.Filters) > 0:
		return c.Filters
	case c.Gerrit.Username == "" || c.Gerrit.Token == "":
		return AnonymousFilters
	}
	return DefaultFilters
}

func Path() string {
	if dir := os.Getenv("XDG_CONFIG_HOME"); dir != "" {
		return filepath.Join(dir, "gorrit", "config.toml")
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "gorrit.toml"
	}
	return filepath.Join(home, ".config", "gorrit", "config.toml")
}

// Load reads the config file if present, then applies GORRIT_URL,
// GORRIT_USERNAME and GORRIT_TOKEN overrides.
func Load() (Config, error) {
	var cfg Config
	_, err := toml.DecodeFile(Path(), &cfg)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return cfg, fmt.Errorf("parse %s: %w", Path(), err)
	}
	if v := os.Getenv("GORRIT_URL"); v != "" {
		cfg.Gerrit.URL = v
	}
	if v := os.Getenv("GORRIT_USERNAME"); v != "" {
		cfg.Gerrit.Username = v
	}
	if v := os.Getenv("GORRIT_TOKEN"); v != "" {
		cfg.Gerrit.Token = v
	}
	cfg.Gerrit.URL = strings.TrimRight(cfg.Gerrit.URL, "/")
	if cfg.Gerrit.URL == "" {
		if errors.Is(err, os.ErrNotExist) {
			return cfg, ErrNotFound
		}
		return cfg, fmt.Errorf("no Gerrit URL: set url under [gerrit] in %s or GORRIT_URL", Path())
	}
	return cfg, nil
}

// Save writes the config file, readable by the owner only since it holds a token.
func Save(cfg Config) error {
	path := Path()
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return err
	}
	defer f.Close()
	enc := toml.NewEncoder(f)
	enc.Indent = ""
	return enc.Encode(cfg)
}
