package ui

import (
	"testing"

	"github.com/arnaudmorin/gorrit/internal/gerrit"
)

func TestIsAutomated(t *testing.T) {
	by := func(name, user, tag string) gerrit.ChangeMessageInfo {
		return gerrit.ChangeMessageInfo{Author: &gerrit.AccountInfo{Name: name, Username: user}, Tag: tag}
	}
	cases := []struct {
		msg  gerrit.ChangeMessageInfo
		want bool
	}{
		{by("Zuul", "zuul", "autogenerated:zuul:check"), true},
		{by("Arista CI", "arista-ci", ""), true},
		{by("Some Human", "human", ""), false},
		{by("Cinder Bot", "cinder-bot", ""), false},
		{by("Cinder Bot", "cinder-bot", ""), false},
	}
	for _, c := range cases {
		if got := isAutomated(c.msg, nil); got != c.want {
			t.Fatalf("%s: got %v", c.msg.Author.Name, got)
		}
	}
	if !isAutomated(by("Cinder Bot", "cinder-bot", ""), []string{"cinder bot"}) {
		t.Fatal("configured bot name not matched")
	}
}
